const DEFAULT_FOLDER_COLOR = "#38bdf8"
const DEFAULT_FILE_META = { Icon: File, color: "#8b949e" }

const normalize = (name = "") => String(name).toLowerCase().trim()

const getExtension = (name) => {
  const lower = normalize(name)
  const dot = lower.lastIndexOf(".")
  return dot > 0 ? lower.slice(dot + 1) : lower
}

export const getFolderColor = (name = "") => {
  const key = normalize(name)
  return FOLDER_COLORS[key] ?? DEFAULT_FOLDER_COLOR
}

export const getFileMeta = (name = "") => {
  const key = normalize(name)

  if (FILE_NAMES[key]) return FILE_NAMES[key]

  const prefix = FILE_NAME_PREFIXES.find(({ prefix: value }) => key.startsWith(value))
  if (prefix) return prefix.meta

  const suffix = FILE_NAME_SUFFIXES.find(({ suffix: value }) => key.endsWith(value))
  if (suffix?.meta) return suffix.meta

  const extension = getExtension(key)
  return FILE_EXTENSIONS[extension] ?? DEFAULT_FILE_META
}

export const getFileColor = (name = "") => getFileMeta(name).color

export default {
  getFolderColor,
  getFileMeta,
  getFileColor,
}
